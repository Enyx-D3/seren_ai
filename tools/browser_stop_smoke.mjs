import { chromium } from 'playwright';
const browser = await chromium.launch({ headless: true });
const page = await browser.newPage();
await page.goto('http://127.0.0.1:8799/');
await page.locator('#settingsBtnTop').click();
await page.locator('#modelFileInput').setInputFiles('workspace/parts/Falcon-H1-Tiny-90M-Instruct-Q4_K_M.gguf');
await page.waitForFunction(() => document.querySelector('#modelRows')?.textContent.includes('Verified'));
await page.locator('#setupDone').click();
await page.locator('#prompt').fill('Write a long, detailed story about a train trip through five cities.');
await page.locator('#sendBtn').click();
await page.waitForFunction(() => document.querySelector('.msg-ai .prose')?.textContent.length > 5);
await page.locator('#sendBtn').click();
await page.waitForFunction(() => document.querySelector('.msg-ai .m-status')?.textContent.includes('Stopped'));
const before = await page.locator('.msg-ai .prose').innerText();
await page.waitForTimeout(1500);
const after = await page.locator('.msg-ai .prose').innerText();
await page.reload();
console.log(JSON.stringify({ status: await page.locator('.msg-ai .m-status').innerText(), stable: before === after,
  persisted: await page.locator('.msg-ai .prose').innerText() === after }, null, 2));
await browser.close();
