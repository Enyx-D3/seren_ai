import { chromium } from 'playwright';
const browser = await chromium.launch({ headless: true });
const page = await browser.newPage();
const errors = [];
page.on('pageerror', e => errors.push(e.message));
page.on('console', m => { if (m.type() === 'error') errors.push(m.text()); });
await page.goto('http://127.0.0.1:8799/');
await page.waitForFunction(() => document.querySelector('#footnote')?.textContent.length > 0, null, { timeout: 120000 });
console.log('boot', await page.locator('#footnote').innerText(), errors);
await page.locator('#settingsBtnTop').click();
await page.locator('#modelFileInput').setInputFiles('workspace/parts/Falcon-H1-Tiny-90M-Instruct-Q4_K_M.gguf');
await page.waitForFunction(() => document.querySelector('#modelRows')?.textContent.includes('Verified'), null, { timeout: 120000 });
console.log('import', await page.locator('#modelRows').innerText());
await page.locator('#setupDone').click();
await page.locator('#prompt').fill('Say hello.');
await page.locator('#sendBtn').click();
await page.waitForFunction(() => document.querySelector('.msg-ai .m-status')?.textContent.includes('Local response'), null, { timeout: 120000 });
console.log('answer', await page.locator('.msg-ai .prose').last().innerText());
console.log('errors', errors);
await browser.close();
